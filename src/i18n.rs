//! Tiny bilingual (English / Simplified Chinese) string catalogue.
//!
//! Deliberately a plain match table: no runtime lookup maps, no allocations and
//! trivially extensible. Every user visible label should come from here.

use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Language {
    En,
    Zh,
}

impl Default for Language {
    fn default() -> Self {
        Self::En
    }
}

impl Language {
    pub fn key(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Zh => "zh",
        }
    }

    pub fn from_key(key: &str) -> Option<Self> {
        match key {
            "en" => Some(Self::En),
            "zh" => Some(Self::Zh),
            _ => None,
        }
    }

    /// Native language name, shown in the language switcher.
    pub fn native_name(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Zh => "中文",
        }
    }

    /// Pick a starting language from the environment.
    pub fn detect() -> Self {
        if let Ok(lang) = std::env::var("LANG") {
            if lang.to_ascii_lowercase().starts_with("zh") {
                return Self::Zh;
            }
        }
        Self::En
    }

    pub fn other(self) -> Self {
        match self {
            Self::En => Self::Zh,
            Self::Zh => Self::En,
        }
    }
}

