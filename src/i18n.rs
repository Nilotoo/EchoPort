/// Look up a translated string.
pub fn t(lang: Language, key: Key) -> &'static str {
    let (en, zh) = key.pair();
    match lang {
        Language::En => en,
        Language::Zh => zh,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn zhen_never_empty() {
        for lang in [Language::En, Language::Zh] {
            assert!(!t(lang, Key::Play).is_empty());
            assert!(!t(lang, Key::PrivacyNote).is_empty());
        }
    }

    #[test]
    fn language_roundtrip() {
        for lang in [Language::En, Language::Zh] {
            assert_eq!(Language::from_key(lang.key()), Some(lang));
        }
        assert_eq!(Language::En.other(), Language::Zh);
    }
}
