#!/usr/bin/env bash
# Build an Arch Linux pacman package (.pkg.tar.zst) from the locally built release binary.
# No root required: the package is assembled in a staging tree and validated with
# `pacman -Qip` / `pacman -Qlp`. The AUR-ready source recipe lives in packaging/arch/PKGBUILD.
#
# Output: dist/echoport-<version>-1-x86_64.pkg.tar.zst (+ .sha256)
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

VERSION=$(tr -d '[:space:]' < VERSION)
PKGNAME=echoport
PKGREL=1
NAME="$PKGNAME-$VERSION-$PKGREL-x86_64"
STAGE="dist/_arch/$PKGNAME"
OUT="dist/$NAME.pkg.tar.zst"
BIN="${ECHOPORT_BIN:-target/release/echoport}"
[ -f "$BIN" ] || { echo "missing $BIN (run: cargo build --release)" >&2; exit 1; }

rm -rf "$STAGE" "$OUT" "$OUT.sha256"
mkdir -p "$STAGE/usr/bin" "$STAGE/usr/share/applications" \
         "$STAGE/usr/share/doc/$PKGNAME/examples" "$STAGE/usr/share/licenses/$PKGNAME" \
         "$STAGE/usr/share/echoport"
for size in 32 48 128 256; do
    mkdir -p "$STAGE/usr/share/icons/hicolor/${size}x${size}/apps"
    if [ "$size" = 256 ]; then
        cp "assets/icon.png" "$STAGE/usr/share/icons/hicolor/256x256/apps/echoport.png"
    else
        cp "assets/icon-$size.png" "$STAGE/usr/share/icons/hicolor/${size}x${size}/apps/echoport.png"
    fi
done
install -m0755 "$BIN" "$STAGE/usr/bin/echoport"
install -m0644 packaging/echoport.desktop "$STAGE/usr/share/applications/echoport.desktop"
install -m0644 README.md LICENSE NOTICE "$STAGE/usr/share/doc/$PKGNAME/"
install -m0644 LICENSE "$STAGE/usr/share/licenses/$PKGNAME/LICENSE"
install -m0644 NOTICE "$STAGE/usr/share/licenses/$PKGNAME/NOTICE"
for doc in SCRIPTING.md PLUGINS.md plugins.html config.html; do
    cp "docs/$doc" "$STAGE/usr/share/doc/$PKGNAME/$doc"
done
for cfg in config.lua config.zh-CN.lua config.en.lua; do
    cp "examples/$cfg" "$STAGE/usr/share/doc/$PKGNAME/examples/$cfg"
done
cp examples/plugins/example.lua "$STAGE/usr/share/doc/$PKGNAME/examples/example.lua"
install -m0644 VERSION "$STAGE/usr/share/echoport/VERSION"

SIZE=$(du -sb "$STAGE" | cut -f1)
{
    echo "# Generated by scripts/package-arch.sh"
    echo "pkgname = $PKGNAME"
    echo "pkgbase = $PKGNAME"
    echo "pkgver = $VERSION-$PKGREL"
    echo "pkgdesc = Local-first music player for YouTube, SoundCloud, Bilibili, Netease, Apple Music and local files"
    echo "url = https://github.com/Nilotoo/EchoPort"
    echo "builddate = $(date +%s)"
    echo "packager = nilotoo <https://github.com/Nilotoo>"
    echo "size = $SIZE"
    echo "arch = x86_64"
    echo "license = GPL-3.0-only"
    echo "depend = glibc"
    echo "depend = gcc-libs"
    echo "optdepend = yt-dlp: stream and download online audio"
    echo "optdepend = ffmpeg: transcode downloaded audio"
} > "$STAGE/.PKGINFO"

( cd "$STAGE" && bsdtar -czf .MTREE --format=mtree \
    --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' .PKGINFO usr )
( cd "$STAGE" && bsdtar -cf - .PKGINFO .MTREE usr | zstd -q -19 -o "$ROOT/$OUT" )
(cd "$(dirname "$OUT")" && sha256sum "$(basename "$OUT")") > "$OUT.sha256"

if command -v pacman >/dev/null 2>&1; then
    echo "==> pacman -Qip:"
    pacman -Qip "$OUT" | head -20
    echo "==> pacman -Qlp (first 20):"
    pacman -Qlp "$OUT" | head -20
else
    echo "==> pacman not available; skipping -Qip/-Qlp validation"
fi
rm -rf "$STAGE"
echo ""
echo "artifact: $OUT"
echo "  size:   $(stat -c %s "$OUT") bytes"
echo "  sha256: $(cut -d' ' -f1 "$OUT.sha256")"
